const HODU_WORDS = [
  { w: 'הוֹדוּ', dir: 0 }, { w: "לַה'", dir: null }, { w: 'כִּי', dir: 1 }, { w: 'טוֹב,', dir: 2 },
  { w: 'כִּי', dir: 3 }, { w: 'לְעוֹלָם', dir: 4 }, { w: 'חַסְדּוֹ.', dir: 5 },
];
const ANA_WORDS = [
  { w: 'אָנָּא', dir: [0, 1] }, { w: "ה'", dir: null }, { w: 'הוֹשִׁיעָה', dir: [2, 3] }, { w: 'נָּא.', dir: [4, 5] },
];
const plain = (t) => t.split(' ').map((w) => ({ w, dir: null }));

/** בונה את שורות ההלל לנוסח נתון. star: נקודת נענוע. */
export function buildHallel(key) {
  const L = [];
  const hodu = (star, tag) => ({ words: HODU_WORDS, star, kind: 'hodu', tag });
  const ana = (star, tag) => ({ words: ANA_WORDS, star, kind: 'ana', tag });
  const line = (t, tag) => ({ words: plain(t), star: false, kind: 'plain', tag });
  if (key === 'ashkenaz') {
    L.push(hodu(true, 'ש"ץ'));
    L.push(hodu(true, 'קהל'));
    L.push(line('יֹאמַר נָא יִשְׂרָאֵל, כִּי לְעוֹלָם חַסְדּוֹ.', 'ש"ץ'));
    L.push(hodu(true, 'קהל'));
    L.push(line('יֹאמְרוּ נָא בֵית אַהֲרֹן, כִּי לְעוֹלָם חַסְדּוֹ.', 'ש"ץ'));
    L.push(hodu(true, 'קהל'));
    L.push(line('יֹאמְרוּ נָא יִרְאֵי ה\', כִּי לְעוֹלָם חַסְדּוֹ.', 'ש"ץ'));
    L.push(hodu(true, 'קהל'));
  } else {
    L.push(hodu(true));
    L.push(line('יֹאמַר נָא יִשְׂרָאֵל, כִּי לְעוֹלָם חַסְדּוֹ.'));
    L.push(line('יֹאמְרוּ נָא בֵית אַהֲרֹן, כִּי לְעוֹלָם חַסְדּוֹ.'));
    L.push(line('יֹאמְרוּ נָא יִרְאֵי ה\', כִּי לְעוֹלָם חַסְדּוֹ.'));
  }
  L.push({ words: plain('· · ·  (המשך ההלל)  · · ·'), star: false, kind: 'gap' });
  L.push(line('זֶה הַיּוֹם עָשָׂה ה\', נָגִילָה וְנִשְׂמְחָה בוֹ.'));
  L.push(ana(true, key === 'ashkenaz' ? 'ש"ץ' : undefined));
  L.push(ana(true, key === 'ashkenaz' ? 'קהל' : undefined));
  L.push(line("אָנָּא ה' הַצְלִיחָה נָּא. אָנָּא ה' הַצְלִיחָה נָּא."));
  L.push(line("בָּרוּךְ הַבָּא בְּשֵׁם ה', בֵּרַכְנוּכֶם מִבֵּית ה'."));
  L.push(line('אֵל ה\' וַיָּאֶר לָנוּ, אִסְרוּ חַג בַּעֲבֹתִים עַד קַרְנוֹת הַמִּזְבֵּחַ.'));
  L.push(line('אֵלִי אַתָּה וְאוֹדֶךָּ, אֱלֹהַי אֲרוֹמְמֶךָּ.'));
  if (key === 'ashkenaz') {
    L.push(hodu(true, 'ש"ץ'));
    L.push(hodu(true, 'קהל'));
  } else {
    L.push(hodu(true));
  }
  return L;
}

